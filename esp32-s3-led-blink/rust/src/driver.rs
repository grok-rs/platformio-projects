//! Інтерфейс виводу кадру на реальні світлодіоди.

use core::fmt::Display;

use crate::Frame;

/// Єдиний шар, який знає про схему підключення; решта програми працює лише з кадрами.
///
/// У C++ це абстрактний клас із `virtual` методами і виклик через vtable. Тут — трейт:
/// [`BlinkPlayer<D>`](crate::BlinkPlayer) узагальнений за `D: LedDriver`, компілятор
/// підставляє конкретний драйвер (мономорфізація), і віртуальних викликів немає.
///
/// `begin()` не потрібен: виводи налаштовує конструктор драйвера, тож «забути викликати
/// `begin()`» неможливо. `describe(Print&)` замінено на [`Display`]: `println!("{driver}")`.
pub trait LedDriver: Display {
    /// Вивести кадр на світлодіоди.
    fn show(&mut self, frame: Frame);

    /// Викликається на кожному тіку головного циклу — для драйверів із часовою нарізкою.
    fn tick(&mut self) {}
}
